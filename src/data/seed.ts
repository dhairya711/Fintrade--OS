// ─── Helper to create order line item ─────────────────────────────────────────

function mkLineItem(
  productId: string,
  qty: number,
  discount: number,
  isInterState: boolean
): OrderLineItem {
  const prod = SEED_PRODUCTS.find((p) => p.id === productId)!;
  const unitPrice = prod.wholesalePrice;
  const gross = unitPrice * qty;
  const discAmt = (gross * discount) / 100;
  const taxableAmount = gross - discAmt;
  const gstRate = 18;
  const taxAmt = taxableAmount * (gstRate / 100);
  const cgst = isInterState ? 0 : taxAmt / 2;
  const sgst = isInterState ? 0 : taxAmt / 2;
  const igst = isInterState ? taxAmt : 0;

  return {
    id: `li-${productId}-${Math.random().toString(36).slice(2, 7)}`,
    productId: prod.id,
    productName: prod.name,
    sku: prod.sku,
    hsn: prod.hsn,
    quantity: qty,
    unitPrice,
    discount,
    taxableAmount,
    gstRate,
    cgst,
    sgst,
    igst,
    lineTotal: taxableAmount + taxAmt,
  };
}

function mkOrder(
  id: string,
  num: string,
  dealer: Dealer,
  items: OrderLineItem[],
  orderStatus: Order['orderStatus'],
  paymentStatus: Order['paymentStatus'],
  paidPct: number,
  daysAgo: number,
  invoiceId?: string,
  shippingInfo?: Order['shippingInfo']
): Order {
  const isInterState = dealer.state !== 'Gujarat';
  const lineItems = items.map((li) => ({
    ...li,
    cgst: isInterState ? 0 : li.taxableAmount * 0.09,
    sgst: isInterState ? 0 : li.taxableAmount * 0.09,
    igst: isInterState ? li.taxableAmount * 0.18 : 0,
    lineTotal: li.taxableAmount * 1.18,
  }));
  const subtotal = lineItems.reduce((s, l) => s + l.quantity * l.unitPrice, 0);
  const totalDiscount = lineItems.reduce(
    (s, l) => s + (l.quantity * l.unitPrice * l.discount) / 100,
    0
  );
  const taxableAmount = lineItems.reduce((s, l) => s + l.taxableAmount, 0);
  const totalCgst = lineItems.reduce((s, l) => s + l.cgst, 0);
  const totalSgst = lineItems.reduce((s, l) => s + l.sgst, 0);
  const totalIgst = lineItems.reduce((s, l) => s + l.igst, 0);
  const grandTotal = taxableAmount + totalCgst + totalSgst + totalIgst;
  const paidAmount = Math.round((grandTotal * paidPct) / 100);
  return {
    id,
    orderNumber: num,
    dealerId: dealer.id,
    dealerName: dealer.name,
    dealerCity: dealer.city,
    dealerState: dealer.state,
    lineItems,
    subtotal,
    totalDiscount,
    taxableAmount,
    totalCgst,
    totalSgst,
    totalIgst,
    grandTotal,
    orderStatus,
    paymentStatus,
    paidAmount,
    invoiceId,
    shippingInfo,
    createdAt: fmtDT(subDays(today, daysAgo)),
    updatedAt: fmtDT(subDays(today, Math.max(0, daysAgo - 2))),
  };
}

