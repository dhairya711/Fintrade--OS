function mkInvoice(ord: Order, dealer: Dealer, invNum: string, daysAgoPaid: number, status: Invoice['status'], paidPct: number): Invoice {
  const grandTotal = ord.grandTotal;
  const paidAmount = Math.round((grandTotal * paidPct) / 100);
  const payments: Payment[] = paidPct > 0 ? [{
    id: `pay-${invNum}`,
    amount: paidAmount,
    method: 'NEFT',
    reference: `NEFT${Math.random().toString().slice(2,12)}`,
    date: fmt(subDays(today, daysAgoPaid)),
  }] : [];
  return {
    id: `inv-${invNum.replace('INV-2026-', '').padStart(3,'0')}`,
    invoiceNumber: invNum,
    orderId: ord.id,
    dealerId: dealer.id,
    dealerName: dealer.name,
    dealerGstin: dealer.gstin,
    dealerAddress: dealer.address,
    dealerCity: dealer.city,
    dealerState: dealer.state,
    lineItems: ord.lineItems,
    subtotal: ord.subtotal,
    totalDiscount: ord.totalDiscount,
    taxableAmount: ord.taxableAmount,
    totalCgst: ord.totalCgst,
    totalSgst: ord.totalSgst,
    totalIgst: ord.totalIgst,
    roundOff: parseFloat((Math.round(grandTotal) - grandTotal).toFixed(2)),
    grandTotal: Math.round(grandTotal),
    paidAmount,
    status,
    payments,
    dueDate: fmt(addDays(new Date(ord.createdAt), 30)),
    sentAt: ord.createdAt,
    createdAt: ord.createdAt,
    updatedAt: ord.updatedAt,
  };
}

